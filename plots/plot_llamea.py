# Run with python -m plots.plot_llamea
# Stage 1 plot: how the LLaMEA search improved over time
# Dots: the fitness (mean AOCC over 10 seeds) of every generated candidate
# Line: the best fitness found so far

import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")   # draw to files, no window needed
import matplotlib.pyplot as plt

from plots.style import clean_axes


# ----------------------------SETTINGS: one entry per LLaMEA run-------------------------


# IMPORTANT: add correct logs paths
LLAMEA_RUNS = [
    (r"llamea_logs\BO_STUB_TASK_PROMPT_1\exp-11-16_113135-LLaMEA-qwen2.5-coder-14b-q4_latest-bo-gen-test\log.jsonl", "evolved on 1124"), # real run
    (r"llamea_logs\BO_STUB_TASK_PROMPT_1\exp-11-16_084035-LLaMEA-qwen2.5-coder-14b-q4_latest-bo-gen-test\log.jsonl", "evolved on f15"), # bbob run
]

OUT_DIR = "plots/output"
COLORS = ["#2a78d6", "#eb6834"]   # same colors as the two LLaMEA algorithms in plots/style.py


# -----------------------------READING A LOG----------------------------------

def load_fitness(log_path):
    # Each line of log.jsonl is one candidate
    # Candidates that crashed have no valid fitness: they count as 0
    fitness = []
    with open(log_path) as f:
        for line in f:
            line = line.strip()
            if line == "":
                continue
            candidate = json.loads(line)
            value = candidate.get("fitness")
            if value is None or not math.isfinite(float(value)):
                value = 0.0
            fitness.append(float(value))
    return fitness


def best_so_far(values):
    result = []
    best = 0.0
    for value in values:
        if value > best:   # higher AOCC is better
            best = value
        result.append(best)
    return result


# -------------------------------------MAIN-----------------------------------------------------

if __name__ == "__main__":
    Path(OUT_DIR).mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(7, 4.5))

    for i in range(len(LLAMEA_RUNS)):
        log_path, label = LLAMEA_RUNS[i]
        color = COLORS[i % len(COLORS)]

        fitness = load_fitness(log_path)
        best = best_so_far(fitness)
        candidates = list(range(1, len(fitness) + 1))   # 1, 2, ..., number of candidates

        ax.scatter(candidates, fitness, s=12, color=color, alpha=0.35, linewidths=0)
        ax.step(candidates, best, where="post", color=color, linewidth=2,
                label=label + ": best = " + str(round(best[-1], 3)))

        n_failed = 0
        for value in fitness:
            if value == 0.0:
                n_failed += 1
        print(label, "|", len(fitness), "candidates | best AOCC =", round(best[-1], 4),
              "| failed or zero =", n_failed)

    ax.set_xlabel("Candidate (order generated by LLaMEA)")
    ax.set_ylabel("Fitness: mean AOCC over 10 seeds")
    ax.set_title("LLaMEA algorithm generation (dots: each candidate, line: best so far)")
    ax.set_ylim(bottom=0)
    clean_axes(ax)
    ax.legend(loc="lower right", facecolor="white", edgecolor="none", framealpha=0.9)
    fig.tight_layout()

    for extension in ["png", "pdf"]:
        fig.savefig(Path(OUT_DIR) / ("llamea_aocc." + extension), dpi=200)
    print("saved:", Path(OUT_DIR) / "llamea_aocc.png")
